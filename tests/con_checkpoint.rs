//! CON checkpoint bytes, restored f64 bits, and a bit-exact resume.
//!
//! The fixture under `tests/fixtures/con_checkpoint.con` is the artifact.
//! This file compares a fresh write with `cmp`. It does not rebuild the
//! expected text.

use std::path::{Path, PathBuf};
use std::process::Command;

use eindir_core::{Bounds, DifferentiableObjective, Gradient, Objective};
use ndarray::{Array1, ArrayView1};
use rgmin::{
    Control, LineSearch, Method, Report, Solver, Status, minimize_method, read_checkpoint,
    write_checkpoint,
};

const HEADER: &str = "Generated by eOn";
const ENERGY: f64 = -3.5;

fn symbols() -> Vec<String> {
    ["Cu", "H", "Cu", "H"]
        .into_iter()
        .map(str::to_string)
        .collect()
}

fn masses() -> [f64; 4] {
    [63.546, 1.00784, 63.546, 1.00784]
}

fn cell() -> [[f64; 3]; 3] {
    [[10.0, 0.0, 0.0], [1.5, 8.0, 0.0], [0.5, 0.5, 6.0]]
}

fn fixed() -> [[bool; 3]; 4] {
    [[true, false, false], [false; 3], [false; 3], [false; 3]]
}

fn coords() -> Array1<f64> {
    Array1::from_vec(vec![
        -0.0,
        1.25,
        f64::from_bits(1),
        f64::from_bits(0x0010_0000_0000_0000),
        -0.5,
        2.0,
        3.0,
        0.0,
        -1.0,
        -2.5,
        4.0,
        0.125,
    ])
}

fn host_report() -> Report {
    Report {
        value: ENERGY,
        coords: coords(),
        steps: 0,
        grad_norm: 0.0,
        status: Status::Iterating,
    }
}

fn fixture() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/con_checkpoint.con")
}

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("rgmin-con-{}-{name}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    dir.join("checkpoint.con")
}

fn write_fixture(path: &Path) {
    write_checkpoint(
        path,
        &host_report(),
        &symbols(),
        &masses(),
        cell(),
        &fixed(),
        HEADER,
    )
    .unwrap();
}

fn assert_bits(got: &[f64], expect: &[f64]) {
    assert_eq!(got.len(), expect.len());
    for (i, (got, expect)) in got.iter().zip(expect).enumerate() {
        assert_eq!(got.to_bits(), expect.to_bits(), "coord {i}");
    }
}

fn top_level_key(json: &str, key: &str) -> bool {
    let needle = format!("\"{key}\"");
    let mut depth = 0i32;
    let mut in_string = false;
    let mut escape = false;
    let bytes = json.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let c = bytes[i];
        if in_string {
            if escape {
                escape = false;
            } else if c == b'\\' {
                escape = true;
            } else if c == b'"' {
                in_string = false;
            }
            i += 1;
            continue;
        }
        match c {
            b'"' => {
                if depth == 1 {
                    let rest = &json[i..];
                    if rest.starts_with(&needle) {
                        let after = rest[needle.len()..].trim_start();
                        if after.starts_with(':') {
                            return true;
                        }
                    }
                }
                in_string = true;
            }
            b'{' => depth += 1,
            b'}' => depth -= 1,
            _ => {}
        }
        i += 1;
    }
    false
}

#[test]
fn write_checkpoint_cmps_the_fixture() {
    let path = scratch("cmp");
    write_fixture(&path);
    let output = Command::new("cmp")
        .arg(&path)
        .arg(fixture())
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "cmp {}\n{}",
        output.status,
        String::from_utf8_lossy(&output.stdout)
    );
    let text = std::fs::read_to_string(&path).unwrap();
    let mut lines = text.lines();
    assert_eq!(lines.next(), Some(HEADER));
    let meta = lines.next().unwrap();
    assert!(top_level_key(meta, "energy"), "{meta}");
    assert!(!text.contains("Forces of Component"));
    assert!(!text.contains("Velocities of Component"));
    let cu = text.find("Coordinates of Component 1").expect("Cu block");
    let h = text.find("Coordinates of Component 2").expect("H block");
    assert!(cu < h, "Cu is the first species");
    let cu_block = &text[cu..h];
    assert!(cu_block.contains(" 1 0\n"), "fixed x on atom 0: {cu_block}");
    assert!(
        cu_block.contains(" 0 2\n"),
        "second Cu keeps its index: {cu_block}"
    );
}

#[test]
fn read_checkpoint_restores_coordinate_and_energy_bits() {
    let (got, energy) = read_checkpoint(fixture()).unwrap();
    assert_eq!(energy.unwrap().to_bits(), ENERGY.to_bits());
    assert_bits(got.as_slice().unwrap(), coords().as_slice().unwrap());
    assert_eq!(got[2].to_bits(), 1);
    assert_eq!(got[3].to_bits(), f64::MIN_POSITIVE.to_bits());
    assert!(got[0].is_sign_negative() && got[0] == 0.0);
}

#[test]
fn non_finite_value_omits_the_energy_key() {
    for value in [f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
        let path = scratch(&format!("nonfinite-{}", value.to_bits()));
        let mut report = host_report();
        report.value = value;
        write_checkpoint(
            &path,
            &report,
            &symbols(),
            &masses(),
            cell(),
            &fixed(),
            HEADER,
        )
        .unwrap();
        let text = std::fs::read_to_string(&path).unwrap();
        let meta = text.lines().nth(1).unwrap();
        assert!(!top_level_key(meta, "energy"), "{meta}");
        let (got, energy) = read_checkpoint(&path).unwrap();
        assert!(energy.is_none());
        assert_bits(got.as_slice().unwrap(), coords().as_slice().unwrap());
    }
}

#[test]
fn length_mismatches_write_nothing() {
    let path = scratch("length");
    let _ = std::fs::remove_file(&path);
    let mut report = host_report();
    report.coords = Array1::from_vec(vec![1.0, 2.0]);
    let err = write_checkpoint(
        &path,
        &report,
        &symbols(),
        &masses(),
        cell(),
        &fixed(),
        HEADER,
    )
    .unwrap_err();
    assert!(
        err.to_string().contains("2") && err.to_string().contains('4'),
        "{err}"
    );
    assert!(!path.exists());

    let err = write_checkpoint(
        path.as_path(),
        &host_report(),
        &symbols(),
        &[63.546, 1.00784],
        cell(),
        &fixed(),
        HEADER,
    )
    .unwrap_err();
    assert!(
        err.to_string().contains('2') && err.to_string().contains('4'),
        "{err}"
    );
    assert!(!path.exists());

    let err = write_checkpoint(
        &path,
        &host_report(),
        &symbols(),
        &masses(),
        cell(),
        &[[true, false, false]],
        HEADER,
    )
    .unwrap_err();
    assert!(
        err.to_string().contains('1') && err.to_string().contains('4'),
        "{err}"
    );
    assert!(!path.exists());
}

#[test]
fn two_masses_for_one_symbol_are_refused() {
    let path = scratch("mass");
    let _ = std::fs::remove_file(&path);
    let mut masses = masses();
    masses[2] = 62.0;
    let err = write_checkpoint(
        &path,
        &host_report(),
        &symbols(),
        &masses,
        cell(),
        &fixed(),
        HEADER,
    )
    .unwrap_err();
    assert!(err.to_string().contains("Cu"), "{err}");
    assert!(err.to_string().contains("62"), "{err}");
    assert!(!path.exists());
}

#[test]
fn awkward_finite_energy_round_trips_its_bits() {
    let path = scratch("energy");
    let energy = f64::from_bits(0x3ff0_0000_0000_0001);
    let mut report = host_report();
    report.value = energy;
    write_checkpoint(&path, &report, &symbols(), &masses(), cell(), &[], HEADER).unwrap();
    let (got, read_energy) = read_checkpoint(&path).unwrap();
    assert_eq!(read_energy.unwrap().to_bits(), energy.to_bits());
    assert_bits(got.as_slice().unwrap(), coords().as_slice().unwrap());
}

struct Bowl {
    n: usize,
    bounds: Bounds<f64>,
}

impl Bowl {
    fn new(n: usize) -> Self {
        Self {
            n,
            bounds: Bounds::new(
                Array1::from_elem(n, -1.0e6),
                Array1::from_elem(n, 1.0e6),
                0.0,
            ),
        }
    }
}

impl Objective<f64> for Bowl {
    fn dim(&self) -> usize {
        self.n
    }
    fn bounds(&self) -> &Bounds<f64> {
        &self.bounds
    }
    fn eval(&self, x: ArrayView1<f64>) -> f64 {
        x.iter()
            .enumerate()
            .map(|(i, v)| 0.5 * (i + 1) as f64 * v * v)
            .sum()
    }
}

impl Gradient<f64> for Bowl {
    fn dim(&self) -> usize {
        self.n
    }
    fn grad(&self, x: ArrayView1<f64>) -> Array1<f64> {
        Array1::from_iter(x.iter().enumerate().map(|(i, v)| (i + 1) as f64 * v))
    }
}

impl DifferentiableObjective<f64> for Bowl {
    fn value_and_gradient(&self, x: ArrayView1<f64>) -> (f64, Array1<f64>) {
        (self.eval(x), self.grad(x))
    }
}

fn control() -> Control {
    Control {
        maxiter: 80,
        gtol: 1e-12,
        istep: 1.0,
        maxmove: None,
        ftol_rel: None,
        noise_floor: None,
    }
}

fn wolfe() -> LineSearch {
    LineSearch::Wolfe {
        c1: 1e-4,
        c2: 0.9,
        maxiter: 20,
    }
}

fn assert_same_report(uninterrupted: &Report, resumed: &Report) {
    assert_eq!(uninterrupted.status, resumed.status);
    assert_eq!(uninterrupted.steps, resumed.steps);
    assert_eq!(uninterrupted.value.to_bits(), resumed.value.to_bits());
    assert_eq!(
        uninterrupted.grad_norm.to_bits(),
        resumed.grad_norm.to_bits()
    );
    assert_bits(
        uninterrupted.coords.as_slice().unwrap(),
        resumed.coords.as_slice().unwrap(),
    );
}

#[test]
fn resumed_minimization_matches_uninterrupted() {
    let obj = Bowl::new(coords().len());
    let (from_file, energy) = read_checkpoint(fixture()).unwrap();
    assert_eq!(energy.unwrap().to_bits(), ENERGY.to_bits());
    assert_bits(from_file.as_slice().unwrap(), coords().as_slice().unwrap());

    for method in [Method::Lbfgs { memory: 5 }, Method::Steepest] {
        let expect_tolerance = matches!(method, Method::Lbfgs { .. });
        let uninterrupted =
            minimize_method(&obj, coords(), &control(), method.clone(), wolfe()).unwrap();
        let resumed =
            minimize_method(&obj, from_file.clone(), &control(), method, wolfe()).unwrap();
        if expect_tolerance {
            assert_eq!(uninterrupted.status, Status::Tolerance);
        }
        assert_same_report(&uninterrupted, &resumed);
    }
}

#[test]
fn checkpoint_of_an_accepted_point_matches_the_in_memory_vector() {
    let obj = Bowl::new(coords().len());
    let mut live = coords();
    let mut solver = Solver::new(Method::Lbfgs { memory: 5 }, control(), live.len());
    for _ in 0..3 {
        solver.step(&obj, &mut live).unwrap();
    }
    let value = obj.value_and_gradient(live.view()).0;
    let report = Report {
        value,
        coords: live.clone(),
        steps: 3,
        grad_norm: 0.0,
        status: Status::Iterating,
    };
    let path = scratch("accepted");
    write_checkpoint(
        &path,
        &report,
        &symbols(),
        &masses(),
        cell(),
        &fixed(),
        HEADER,
    )
    .unwrap();
    let (from_file, energy) = read_checkpoint(&path).unwrap();
    assert_eq!(energy.unwrap().to_bits(), value.to_bits());
    assert_bits(from_file.as_slice().unwrap(), live.as_slice().unwrap());

    let uninterrupted =
        minimize_method(&obj, live, &control(), Method::Lbfgs { memory: 5 }, wolfe()).unwrap();
    let resumed = minimize_method(
        &obj,
        from_file,
        &control(),
        Method::Lbfgs { memory: 5 },
        wolfe(),
    )
    .unwrap();
    assert_same_report(&uninterrupted, &resumed);
}

